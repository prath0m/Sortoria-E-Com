"""Build Sartoria's logo assets from Inter glyph outlines (semibold instance of the variable font).

Outputs (all regenerated on each run):
  frontend/public/brand/sartoria-wordmark.svg        near-black wordmark
  frontend/public/brand/sartoria-wordmark-light.svg  white wordmark, for dark bands and emails
  frontend/public/brand/sartoria-monogram.svg        white S in a near-black rounded square
  frontend/public/favicon.svg                        the monogram, for browser tabs
  frontend/src/components/brand/logoPaths.ts         path data for the React components
  backend/static/brand/*.png                         raster copies for email clients and PDFs

Run from the repo root:  backend/.venv/bin/python scripts/build_brand_assets.py
"""

from pathlib import Path

import cairosvg
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "frontend/node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2"
INK = "#0A0A0A"
WHITE = "#FFFFFF"


def inter(weight: int) -> TTFont:
    return instantiateVariableFont(TTFont(FONT), {"wght": weight})


def glyph_run(font: TTFont, text: str, tracking_em: float):
    """Return (svg path, bounds) for `text` laid out with letter-spacing, baseline at y=0."""
    glyph_set = font.getGlyphSet()
    cmap = font.getBestCmap()
    tracking = tracking_em * font["head"].unitsPerEm
    pen = SVGPathPen(glyph_set, ntos=lambda n: f"{n:.1f}".rstrip("0").rstrip("."))
    bounds = BoundsPen(glyph_set)
    x = 0.0
    names = [cmap[ord(ch)] for ch in text]
    for i, name in enumerate(names):
        # Flip Y so the SVG coordinate system matches the font baseline at y=0.
        glyph_set[name].draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        glyph_set[name].draw(TransformPen(bounds, (1, 0, 0, -1, x, 0)))
        x += glyph_set[name].width + (tracking if i < len(names) - 1 else 0)
    return pen.getCommands(), bounds.bounds


def wordmark():
    path, (x_min, y_min, x_max, y_max) = glyph_run(inter(620), "SARTORIA", 0.18)
    pad = 16
    return {
        "viewBox": f"{x_min - pad:.0f} {y_min - pad:.0f} {x_max - x_min + pad * 2:.0f} {y_max - y_min + pad * 2:.0f}",
        "letters": path,
    }


def monogram():
    path, (x_min, y_min, x_max, y_max) = glyph_run(inter(650), "S", 0)
    size, target_h = 1000, 560
    scale = target_h / (y_max - y_min)
    tx = size / 2 - (x_min + (x_max - x_min) / 2) * scale
    ty = size / 2 - (y_min + (y_max - y_min) / 2) * scale
    return {
        "viewBox": f"0 0 {size} {size}",
        "letter": path,
        "transform": f"matrix({scale:.5f} 0 0 {scale:.5f} {tx:.2f} {ty:.2f})",
        "radius": 220,
    }


def wordmark_svg(w, fill=INK):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{w["viewBox"]}" role="img" aria-label="Sartoria">'
        f'<path fill="{fill}" d="{w["letters"]}"/></svg>'
    )


def monogram_svg(m, background=INK, letter=WHITE):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{m["viewBox"]}" role="img" aria-label="Sartoria">'
        f'<rect width="1000" height="1000" rx="{m["radius"]}" fill="{background}"/>'
        f'<path fill="{letter}" transform="{m["transform"]}" d="{m["letter"]}"/></svg>'
    )


def main():
    w, m = wordmark(), monogram()
    public = ROOT / "frontend/public"
    (public / "brand").mkdir(parents=True, exist_ok=True)
    (public / "brand/sartoria-wordmark.svg").write_text(wordmark_svg(w))
    (public / "brand/sartoria-wordmark-light.svg").write_text(wordmark_svg(w, fill=WHITE))
    (public / "brand/sartoria-monogram.svg").write_text(monogram_svg(m))
    favicon = monogram_svg(m)
    (public / "favicon.svg").write_text(favicon)

    static = ROOT / "backend/static/brand"
    static.mkdir(parents=True, exist_ok=True)
    cairosvg.svg2png(bytestring=wordmark_svg(w).encode(), write_to=str(static / "wordmark.png"), output_width=720)
    cairosvg.svg2png(
        bytestring=wordmark_svg(w, fill=WHITE).encode(), write_to=str(static / "wordmark-light.png"), output_width=720
    )
    cairosvg.svg2png(bytestring=monogram_svg(m).encode(), write_to=str(static / "monogram.png"), output_width=256)
    cairosvg.svg2png(bytestring=favicon.encode(), write_to=str(public / "apple-touch-icon.png"), output_width=180)
    cairosvg.svg2png(bytestring=favicon.encode(), write_to=str(public / "icon-512.png"), output_width=512)
    (static / "wordmark.svg").write_text(wordmark_svg(w))
    (static / "monogram.svg").write_text(monogram_svg(m))

    ts = ROOT / "frontend/src/components/brand/logoPaths.ts"
    ts.write_text(
        "// Generated by scripts/build_brand_assets.py from Inter outlines. Do not edit.\n"
        f"export const WORDMARK = {{\n  viewBox: '{w['viewBox']}',\n  letters: '{w['letters']}',\n}} as const;\n\n"
        f"export const MONOGRAM = {{\n  viewBox: '{m['viewBox']}',\n  letter: '{m['letter']}',\n"
        f"  transform: '{m['transform']}',\n  radius: {m['radius']},\n}} as const;\n"
    )
    print("brand assets written")


if __name__ == "__main__":
    main()
